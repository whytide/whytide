// `pnpm modules:generate` (README "Modules"): writes src/modules.generated.ts, a loader for every
// core/modules/<name>/index.ts, so that a module joins the api by existing, with no edit to the host
// (docs/rules/coding.md §3). `_` and `.` folders, the template among them, are not modules. A loader
// imports the module's build, dist/index.js, by a path the compiler does not follow, so the api
// compiles without the modules. build, typecheck and dev run this first; git ignores the file.
//   node scripts/modules-generate.ts [modules folder] [output file]
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const api = resolve(import.meta.dirname, "..");
/** Where the generated file runs from once compiled: the loaders' paths start there. */
const compiled = join(api, "dist", "src");

/** The modules under `dir`, sorted: the folders with an index.ts, but `_` and `.` ones. */
export function listModules(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !/^[._]/.test(entry.name))
    .filter((entry) => existsSync(join(dir, entry.name, "index.ts")))
    .map((entry) => entry.name)
    .sort();
}

export function moduleListSource(dir: string, names: readonly string[]): string {
  const entries = names.map((name) => {
    const path = relative(compiled, join(dir, name, "dist", "index.js")).replaceAll("\\", "/");
    return `  { name: ${JSON.stringify(name)}, load: () => load(${JSON.stringify(path)}) },\n`;
  });
  return [
    '// Generated by scripts/modules-generate.ts from core/modules/*/index.ts; never committed (README "Modules").',
    'import type { ModuleLoader } from "./modules.ts";',
    "",
    "const load = (path: string): Promise<unknown> => import(new URL(path, import.meta.url).href);",
    "",
    `export const moduleLoaders: readonly ModuleLoader[] = [${entries.length ? `\n${entries.join("")}` : ""}];`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  const dir = resolve(process.argv[2] ?? join(api, "..", "..", "modules"));
  const out = resolve(process.argv[3] ?? join(api, "src", "modules.generated.ts"));
  const names = listModules(dir);
  const text = moduleListSource(dir, names);
  // Written only when it changed: the api's `tsc -b` may be reading it.
  if (!existsSync(out) || readFileSync(out, "utf8") !== text) writeFileSync(out, text);
  process.stdout.write(`modules: ${names.length ? names.join(", ") : "none"}\n`);
}
