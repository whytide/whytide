// `pnpm web:routes` (README "Routes"): the generated part of the app, from every module's ui/nav.ts,
// never committed: a page under app/w/[workspace]/(modules)/<segment>/ that re-exports the module's
// screen, or hands it its panels when it has slots, as "Up next" has (gamma-p4-090), one under
// (modules)/<path>/ for each of its `pages` outside the navigation, which hands the
// page the `panels` other modules put in its slots, a public page under app/(public)/<path>/ for
// each of its `publicPages`, the components of its `slots` in the shell's header or on the
// workspace's home (src/shell/slots.generated.tsx), the navigation
// (src/shell/nav.generated.ts), the bundle of every messages/<locale>.json
// (src/i18n/messages.generated.json) and, for development, the /dev/ui gallery. --fixtures adds the
// test modules of tests/fixtures/modules/; --production, which `build` passes, leaves the gallery out and
// first runs the message-key check, failing on any finding.
//   node scripts/web-routes.ts [--fixtures | --production]
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative, sep } from "node:path";
import { pathToFileURL } from "node:url";
import { z } from "zod";
import { checkMessages, formatProblem } from "../../../packages/platform/i18n/check.ts";
import { isMessageKey } from "../../../packages/platform/i18n/keys.ts";
import { defaultLocale } from "../../../packages/platform/i18n/locale.ts";
import { loadMessages, type MessageRoot } from "../../../packages/platform/i18n/messages.ts";
import { DEFAULT_ICON, GROUPS, type Group, type NavGroup } from "../src/shell/nav.ts";

const name = z.string().regex(/^[a-z][a-z0-9-]*$/);
const entrySchema = z.strictObject({
  group: z.enum(Object.keys(GROUPS) as [Group, ...Group[]]),
  labelKey: z.string().refine(isMessageKey, "not a message key, module.screen.purpose"),
  segment: name,
  screen: name,
  order: z.number().int(),
  /** A Lucide icon by its export name (`Building2`), from @whytide/ui/icons; DEFAULT_ICON without. */
  icon: z
    .string()
    .regex(/^[A-Z][A-Za-z0-9]*$/)
    .optional(),
});

/** A page outside the workspaces, at `path` (`sign-in/sent`): none under /w, /api or /dev. */
const pageSchema = z.strictObject({
  path: z
    .string()
    .regex(/^[a-z][a-z0-9-]*(?:\/[a-z][a-z0-9-]*)*$/)
    .refine((path) => !/^(?:w|api|dev)(?:\/|$)/.test(path), "under /w, /api or /dev"),
  screen: name,
});
/** A component of the shell's header or the workspace home, ui/<screen>/slot.tsx, given SlotProps. */
const slotSchema = z.strictObject({ slot: z.enum(["balance", "home", "sign-out"]), screen: name });
/** A page of the workspace outside the navigation, at /w/<workspace>/<path>; `[name]` is a param. */
const workspacePageSchema = z.strictObject({
  path: z
    .string()
    .regex(
      /^(?:[a-z][a-z0-9-]*|\[[a-z][a-zA-Z0-9]*\])(?:\/(?:[a-z][a-z0-9-]*|\[[a-z][a-zA-Z0-9]*\]))*$/,
    ),
  screen: name,
});
/** A component, ui/<screen>/panel.tsx, in a slot of another module's page, `<module>.<screen>`. */
const panelSchema = z.strictObject({
  page: z.string().regex(/^[a-z][a-z0-9-]*\.[a-z][a-z0-9-]*$/, "not <module>.<screen>"),
  slot: name,
  screen: name,
});
type Mount = { readonly dir: string; readonly file: string; readonly screen: string };
export type PublicPage = Mount & { readonly path: string };
export type Slot = Mount & { readonly slot: string };
/** `id` is `<module>.<screen>`; `slots`, the names its ui/<screen>/slots.ts lists, if it has one. */
export type WorkspacePage = PublicPage & {
  readonly id: string;
  readonly slots?: readonly string[];
};
export type Panel = Mount & { readonly page: string; readonly slot: string };

export type NavEntry = z.infer<typeof entrySchema> & {
  /** The module's folder; `file` is its nav.ts relative to the root, as the errors name it. */
  readonly dir: string;
  readonly file: string;
};

const GALLERY = `// Generated by scripts/web-routes.ts for development; never committed nor built for production.
import { Gallery } from "@whytide/ui/gallery";
import { notFound } from "next/navigation";

export default function GalleryPage() {
  if (process.env.NODE_ENV !== "development") notFound();
  return <Gallery />;
}
`;

/** The folders of the modules (never `_template`), and of the host's test modules with `fixtures`. */
export function moduleDirs(root: string, fixtures: boolean): string[] {
  const parents = [join(root, "core", "modules")];
  if (fixtures) parents.push(join(root, "core", "apps", "web", "tests", "fixtures", "modules"));
  return parents.flatMap((parent) =>
    existsSync(parent)
      ? readdirSync(parent, { withFileTypes: true })
          .filter((entry) => entry.isDirectory() && !/^[_.]/.test(entry.name))
          .map((entry) => join(parent, entry.name))
          .sort()
      : [],
  );
}

/** Every entry of the modules' ui/nav.ts, checked; a segment declared twice fails, naming both files. */
export async function collect(root: string, fixtures: boolean): Promise<NavEntry[]> {
  const entries: NavEntry[] = [];
  const declared = new Map<string, string>();
  for (const dir of moduleDirs(root, fixtures)) {
    const path = join(dir, "ui", "nav.ts");
    if (!existsSync(path)) continue;
    const file = relative(root, path).split(sep).join("/");
    const { nav = [] } = (await import(pathToFileURL(path).href)) as { nav?: unknown };
    const parsed = z.array(entrySchema).safeParse(nav);
    if (!parsed.success) {
      throw new Error(`${file}: \`export const nav\`, ${z.prettifyError(parsed.error)}`);
    }
    for (const entry of parsed.data) {
      if (!existsSync(join(dir, "ui", entry.screen, "page.tsx"))) {
        throw new Error(`${file}: the screen ${entry.screen} has no ui/${entry.screen}/page.tsx`);
      }
      const first = declared.get(entry.segment);
      if (first)
        throw new Error(`the segment ${entry.segment} is declared twice: ${first} and ${file}`);
      declared.set(entry.segment, file);
      entries.push({ ...entry, dir, file });
    }
  }
  return entries;
}

/** The names a screen's ui/<screen>/slots.ts lists, or undefined when it has none. */
async function slotsOf(dir: string, file: string, screen: string): Promise<string[] | undefined> {
  const names = join(dir, "ui", screen, "slots.ts");
  if (!existsSync(names)) return undefined;
  const read = z.array(name).safeParse((await import(pathToFileURL(names).href)).slots);
  if (!read.success) throw new Error(`${file}: ui/${screen}/slots.ts: \`slots\``);
  return read.data;
}

/**
 * The modules' `publicPages`, `slots`, `pages` and `panels`, and the navigation's screens that list
 * slots (`navPages`), checked: a path or a slot declared twice fails, and so does a panel whose page
 * has no such slot.
 */
export async function collectMounts(root: string, fixtures: boolean) {
  const pages: PublicPage[] = [];
  const slots: Slot[] = [];
  const workspacePages: WorkspacePage[] = [];
  const navPages: WorkspacePage[] = [];
  const panels: Panel[] = [];
  const declared = new Map<string, string>();
  for (const dir of moduleDirs(root, fixtures)) {
    const path = join(dir, "ui", "nav.ts");
    if (!existsSync(path)) continue;
    const file = relative(root, path).split(sep).join("/");
    const loaded = (await import(pathToFileURL(path).href)) as Record<string, unknown>;
    const parsed = z
      .strictObject({
        publicPages: z.array(pageSchema),
        slots: z.array(slotSchema),
        pages: z.array(workspacePageSchema),
        panels: z.array(panelSchema),
      })
      .partial()
      .safeParse({
        publicPages: loaded.publicPages,
        slots: loaded.slots,
        pages: loaded.pages,
        panels: loaded.panels,
      });
    if (!parsed.success) throw new Error(`${file}: ${z.prettifyError(parsed.error)}`);
    const {
      publicPages = [],
      slots: own = [],
      pages: inside = [],
      panels: parts = [],
    } = parsed.data;
    const mounts = [
      ...publicPages.map((page) => ({ ...page, id: `the page /${page.path}`, source: "page" })),
      ...own.map((slot) => ({ ...slot, id: `the slot ${slot.slot}`, source: "slot" })),
      ...inside.map((page) => ({ ...page, id: `the page /w/…/${page.path}`, source: "page" })),
      ...parts.map((panel) => ({
        ...panel,
        id: `the panel ${basename(dir)}.${panel.screen} in ${panel.page}`,
        source: "panel",
      })),
    ];
    for (const { id, screen, source } of mounts) {
      if (!existsSync(join(dir, "ui", screen, `${source}.tsx`))) {
        throw new Error(`${file}: ${id} has no ui/${screen}/${source}.tsx`);
      }
      const first = declared.get(id);
      if (first) throw new Error(`${id} is declared twice: ${first} and ${file}`);
      declared.set(id, file);
    }
    pages.push(...publicPages.map((page) => ({ ...page, dir, file })));
    slots.push(...own.map((slot) => ({ ...slot, dir, file })));
    for (const page of inside) {
      const named = await slotsOf(dir, file, page.screen);
      const id = `${basename(dir)}.${page.screen}`;
      workspacePages.push({ ...page, dir, file, id, ...(named && { slots: named }) });
    }
    // collect() checks the navigation's entries: here only their screens' slots are read.
    const screens = z.array(z.looseObject({ segment: name, screen: name })).safeParse(loaded.nav);
    for (const { segment, screen } of screens.success ? screens.data : []) {
      const named = await slotsOf(dir, file, screen);
      const id = `${basename(dir)}.${screen}`;
      if (named) navPages.push({ path: segment, screen, dir, file, id, slots: named });
    }
    panels.push(...parts.map((panel) => ({ ...panel, dir, file })));
  }
  for (const { page, slot, file } of panels) {
    const known = [...workspacePages, ...navPages].find(({ id }) => id === page)?.slots;
    if (!known) throw new Error(`${file}: a panel names the page ${page}, which has no slots`);
    if (!known.includes(slot)) {
      throw new Error(
        `${file}: the slot ${slot} is none of the page ${page}'s: ${known.join(", ")}`,
      );
    }
  }
  return { pages, slots, workspacePages, navPages, panels };
}

/** A page of the workspace's route: the page with the panels of its slots, or the page alone. */
function workspaceRoute(target: string, page: WorkspacePage, panels: readonly Panel[]): string {
  const from = (dir: string, screen: string, source: string) =>
    relative(dirname(target), join(dir, "ui", screen, source))
      .split(sep)
      .join("/");
  const screen = from(page.dir, page.screen, "page.tsx");
  if (!page.slots) return `export { default } from "${screen}";\n`;
  const own = panels.filter((panel) => panel.page === page.id);
  const imports = own.map(
    ({ dir, screen }, index) => `import Panel${index} from "${from(dir, screen, "panel.tsx")}";\n`,
  );
  const bySlot = page.slots.flatMap((slot) => {
    const names = own.flatMap((panel, index) => (panel.slot === slot ? [`Panel${index}`] : []));
    return names.length === 0 ? [] : [`  "${slot}": [${names.join(", ")}],\n`];
  });
  return `import Page from "${screen}";\n${imports.join("")}\nconst panels = {\n${bySlot.join("")}};\n\nexport default function Route(props: Omit<Parameters<typeof Page>[0], "panels">) {\n  return <Page {...props} panels={panels} />;\n}\n`;
}

/** The groups in their order, those with an entry only, each entry by `order`, then by segment. */
export function navigation(entries: readonly NavEntry[]): NavGroup<string>[] {
  return Object.entries(GROUPS).flatMap(([group, labelKey]) => {
    const own = entries
      .filter((entry) => entry.group === group)
      .sort((a, b) => a.order - b.order || a.segment.localeCompare(b.segment));
    const shown = own.map(({ labelKey, segment, icon = DEFAULT_ICON }) => ({
      labelKey,
      segment,
      icon,
    }));
    return shown.length === 0 ? [] : [{ group: group as Group, labelKey, entries: shown }];
  });
}

/** The message-key check of the repository at `root`, thrown with every finding. */
export function checkBundle(root: string): void {
  const { problems } = checkMessages(root);
  if (problems.length === 0) return;
  const lines = problems.map((problem) => `  ${formatProblem(problem)}`);
  throw new Error(["the message-key check failed:", ...lines].join("\n"));
}

/** Writes the generated files of the host at core/apps/web; returns the number of screens. */
export async function writeRoutes(root: string, mode: { fixtures: boolean; production: boolean }) {
  if (mode.production) checkBundle(root);
  const entries = await collect(root, mode.fixtures);
  const web = join(root, "core", "apps", "web");
  const pages = join(web, "app", "w", "[workspace]", "(modules)");
  for (const entry of readdirSync(pages, { withFileTypes: true })) {
    if (entry.isDirectory()) rmSync(join(pages, entry.name), { recursive: true });
  }
  const mounts = await collectMounts(root, mode.fixtures);
  for (const entry of entries) {
    const page = join(pages, entry.segment, "page.tsx");
    const screen = relative(dirname(page), join(entry.dir, "ui", entry.screen, "page.tsx"));
    const id = `${basename(entry.dir)}.${entry.screen}`;
    const slotted = mounts.navPages.find((navPage) => navPage.id === id);
    const source = slotted
      ? workspaceRoute(page, slotted, mounts.panels)
      : `export { default } from "${screen.split(sep).join("/")}";\n`;
    write(
      page,
      `// Generated by scripts/web-routes.ts from ${entry.file}; never committed.\n${source}`,
    );
  }
  const { pages: publicPages, slots } = mounts;
  for (const page of mounts.workspacePages) {
    const target = join(pages, ...page.path.split("/"), "page.tsx");
    if (existsSync(target)) throw new Error(`${page.file}: the page ${page.path} is a segment too`);
    const source = workspaceRoute(target, page, mounts.panels);
    write(
      target,
      `// Generated by scripts/web-routes.ts from ${page.file}; never committed.\n${source}`,
    );
  }
  const open = join(web, "app", "(public)");
  rmSync(open, { recursive: true, force: true });
  for (const page of publicPages) {
    const target = join(open, ...page.path.split("/"), "page.tsx");
    const screen = relative(dirname(target), join(page.dir, "ui", page.screen, "page.tsx"));
    const source = `export { default } from "${screen.split(sep).join("/")}";\n`;
    write(
      target,
      `// Generated by scripts/web-routes.ts from ${page.file}; never committed.\n${source}`,
    );
  }
  const shell = join(web, "src", "shell");
  const imports = slots.map(({ dir, screen }, index) => {
    const path = relative(shell, join(dir, "ui", screen, "slot.tsx"))
      .split(sep)
      .join("/");
    return `import Slot${index} from "${path}";\n`;
  });
  const named = slots.map(({ slot }, index) => `  "${slot}": Slot${index},\n`);
  write(
    join(shell, "slots.generated.tsx"),
    `// Generated by scripts/web-routes.ts; never committed.\nimport type { ComponentType } from "react";\n${imports.join("")}\n/** What the shell gives a slot's component. */\nexport type SlotProps = { readonly email: string; readonly workspaceId: string };\n\nexport const slots: Readonly<Record<string, ComponentType<SlotProps>>> = {\n${named.join("")}};\n`,
  );
  rmSync(join(web, "app", "dev"), { recursive: true, force: true });
  if (!mode.production) write(join(web, "app", "dev", "ui", "page.tsx"), GALLERY);
  // Each entry's icon, a string in the JSON, becomes the icon's import.
  const groups = navigation(entries);
  const icons = [...new Set(groups.flatMap((group) => group.entries.map((e) => e.icon)))].sort();
  const json = JSON.stringify(groups, null, 2).replace(/"icon": "(\w+)"/g, '"icon": $1');
  write(
    join(web, "src", "shell", "nav.generated.ts"),
    `// Generated by scripts/web-routes.ts; never committed.\nimport { ${icons.join(", ")} } from "@whytide/ui/icons";\nimport type { NavGroup } from "./nav.ts";\n\nexport const navigation: NavGroup[] = ${json};\n`,
  );
  const extraRoots: MessageRoot[] = mode.fixtures
    ? moduleDirs(root, true)
        .filter((dir) => !dir.startsWith(join(root, "core", "modules")))
        .map((dir) => ({ module: basename(dir), dir, kind: "module" }))
    : [];
  const locale = defaultLocale();
  const messages = loadMessages(locale, { root, extraRoots });
  write(
    join(web, "src", "i18n", "messages.generated.json"),
    `${JSON.stringify({ locale, messages }, null, 2)}\n`,
  );
  return entries.length;
}

function write(path: string, text: string): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const mode = { fixtures: args.includes("--fixtures"), production: args.includes("--production") };
  if (
    args.some((arg) => arg !== "--fixtures" && arg !== "--production") ||
    (mode.fixtures && mode.production)
  ) {
    process.stderr.write("usage: node scripts/web-routes.ts [--fixtures | --production]\n");
    process.exit(2);
  }
  try {
    const screens = await writeRoutes(join(import.meta.dirname, "..", "..", "..", ".."), mode);
    process.stdout.write(`web:routes: ${screens} screens\n`);
  } catch (error) {
    const details = (error as { details?: unknown }).details;
    const reason = details === undefined ? "" : ` ${JSON.stringify(details)}`;
    process.stderr.write(
      `web:routes: ${error instanceof Error ? error.message : error}${reason}\n`,
    );
    process.exitCode = 1;
  }
}
