// `pnpm client:generate` (README "The API client"): the api's typed client, written to
// src/api/client.generated.ts (git-ignored) from core/apps/api/openapi.generated.json: the types of
// openapi-typescript and openapi-fetch's createClient over them. Its second line holds the document's
// SHA-256, so the file is rewritten only when the document changed; with --check, which `typecheck`
// runs, a client older than the document fails and a missing one is written.
//   node scripts/client-generate.ts [--check] [document] [output]
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const web = resolve(import.meta.dirname, "..");
const args = process.argv.slice(2);
const paths = args.filter((arg) => arg !== "--check").map((arg) => resolve(arg));
const document = paths[0] ?? join(web, "..", "api", "openapi.generated.json");
const output = paths[1] ?? join(web, "src", "api", "client.generated.ts");
const shown = relative(process.cwd(), output);

const text = readFileSync(document, "utf8");
const stamp = `// document sha256 ${createHash("sha256").update(text).digest("hex")}`;
const current = existsSync(output) ? readFileSync(output, "utf8") : undefined;
if (current?.split("\n")[1] === stamp) {
  say(`client: ${shown} is up to date`);
} else if (args.includes("--check") && current !== undefined) {
  fail(`client: ${shown} is older than the api's document: run pnpm client:generate`);
} else if (text.includes('"$ref"')) {
  // openapi:build writes none: the generator then reads nothing but this file.
  fail("client: the document has a $ref, which pnpm openapi:build never writes");
} else {
  const types = astToString(await openapiTS(JSON.parse(text), { silent: true }));
  const source = [
    "// Generated by scripts/client-generate.ts from the api's OpenAPI document; never committed.",
    stamp,
    'import createClient, { type ClientOptions } from "openapi-fetch";',
    "",
    types.trimEnd(),
    "",
    "/** The api's client: `baseUrl` is the api's origin; the browser sends the session cookie. */",
    "export const createApiClient = (options?: ClientOptions) => createClient<paths>(options);",
    "",
  ].join("\n");
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, source);
  say(`client: ${shown} written`);
}

function say(line: string): void {
  process.stdout.write(`${line}\n`);
}

function fail(line: string): void {
  process.stderr.write(`${line}\n`);
  process.exitCode = 1;
}
