// `pnpm -F worker modules:generate` (README "Modules"): writes src/modules.generated.ts, a loader
// for every core/modules/<name> with an events.ts or a workflows/index.ts, and
// src/workflows.generated.ts, the bundle's entry: the smoke workflow and every module's
// workflows/workflows.ts. A module joins the worker by existing (docs/rules/coding.md §3); `_` and
// `.` folders, the template among them, are not modules. Both import the modules' builds, dist/, as
// the api host does, by paths the compiler does not follow: `@whytide/<name>` resolves to the same
// files, so a module another one imports loads once. build and typecheck run this first, and build
// then builds the modules (scripts/modules-build.ts); git ignores both.
//   node scripts/modules-generate.ts [modules folder] [output folder]
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

/** What the worker imports of a module, the build's file, when the source exists. */
const FILES = {
  events: ["events.ts", "dist/events.js"],
  workflows: ["workflows/index.ts", "dist/workflows/index.js"],
} as const;
const ENTRY = ["workflows/workflows.ts", "dist/workflows/workflows.js"] as const;
const HEADER = '// Generated by scripts/modules-generate.ts; never committed (README "Modules").';

/** The modules under `dir`, sorted: its folders but `_` and `.` ones. */
export function listModules(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !/^[._]/.test(entry.name))
    .map((entry) => entry.name)
    .sort();
}

/** The two files' text, with paths relative to `out`, the folder they are written to. */
export function generatedSources(dir: string, out: string): { modules: string; workflows: string } {
  const path = (file: string) => JSON.stringify(relative(out, file).replaceAll("\\", "/"));
  const loaders: string[] = [];
  const entries = ['export * from "./smoke-workflow.ts";'];
  for (const name of listModules(dir)) {
    const found = Object.entries(FILES).filter(([, [source]]) =>
      existsSync(join(dir, name, source)),
    );
    const fields = found.map(
      ([key, [, built]]) => `${key}: () => load(${path(join(dir, name, built))})`,
    );
    if (fields.length) loaders.push(`  { name: ${JSON.stringify(name)}, ${fields.join(", ")} },\n`);
    if (existsSync(join(dir, name, ENTRY[0])))
      entries.push(`export * from ${path(join(dir, name, ENTRY[1]))};`);
  }
  const modules = [
    HEADER,
    'import type { ModuleLoader } from "./modules.ts";',
    "",
    "const load = (path: string): Promise<unknown> => import(new URL(path, import.meta.url).href);",
    "",
    `export const moduleLoaders: readonly ModuleLoader[] = [${loaders.length ? `\n${loaders.join("")}` : ""}];`,
    "",
  ].join("\n");
  return { modules, workflows: [HEADER, ...entries, ""].join("\n") };
}

if (import.meta.main) {
  const dir = resolve(process.argv[2] ?? join(import.meta.dirname, "..", "..", "..", "modules"));
  const out = resolve(process.argv[3] ?? join(import.meta.dirname, "..", "src"));
  const { modules, workflows } = generatedSources(dir, out);
  // Each written only when it changed: the worker's `tsc -b` may be reading it.
  const write = (file: string, text: string) => {
    if (!existsSync(file) || readFileSync(file, "utf8") !== text) writeFileSync(file, text);
  };
  write(join(out, "modules.generated.ts"), modules);
  write(join(out, "workflows.generated.ts"), workflows);
  process.stdout.write(`worker modules: ${listModules(dir).join(", ") || "none"}\n`);
}
