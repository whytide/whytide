// Unit tests of the registry's selection (alpha-p1-090): the generated loaders from a folder tree, the
// adapters registered for a port, the one adapter a selector names loaded and bound once, nothing
// kept when a step fails.
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";
import { isAppError } from "@whytide/platform";
import { knownAdapterNames, resolveAdapter } from "../_pattern/adapter.ts";
import { listAdapters, registrySource } from "../_pattern/generate.ts";
import { defineAdapter, getAdapter, registeredAdapters } from "../index.ts";
import { echoAdapter, greeter } from "./fixtures/pattern/fixture/echo/index.ts";
import { fixtureFakeAdapter } from "./fixtures/pattern/fixture/fake/index.ts";
import { fixturePort } from "./fixtures/pattern/fixture/port.ts";

const LOADERS_TYPE = "Readonly<Record<string, () => Promise<unknown>>>";

test("the generated loaders name every <port>/<adapter>/index.ts under a folder with a port.ts, sorted", () => {
  const fixtures = fileURLToPath(new URL("./fixtures/pattern/", import.meta.url));
  assert.deepEqual(listAdapters(fixtures), [
    "fixture/broken",
    "fixture/echo",
    "fixture/fake",
    "fixture/lazy",
    "fixture/needs-key",
  ]);
  const dir = mkdtempSync(join(tmpdir(), "whytide-registry-"));
  try {
    const files = [
      "llm/port.ts",
      "llm/fake/index.ts",
      "llm/anthropic/index.ts",
      "llm/anthropic/tests/contract.test.ts",
      "llm/tests/index.ts",
      "llm/testing/index.ts",
      "llm/docs/README.md",
      "_pattern/x/index.ts",
      "orphan/vendor/index.ts",
    ];
    for (const file of files) {
      mkdirSync(dirname(join(dir, file)), { recursive: true });
      writeFileSync(join(dir, file), "");
    }
    const adapters = listAdapters(dir);
    assert.deepEqual(adapters, ["llm/anthropic", "llm/fake"]);
    const source = registrySource(adapters);
    assert.match(source, /^\/\/ Generated by _pattern\/generate\.ts/);
    assert.deepEqual(source.split("\n").slice(1), [
      `export const adapterLoaders: ${LOADERS_TYPE} = {`,
      '  "llm/anthropic": () => import("./llm/anthropic/index.ts"),',
      '  "llm/fake": () => import("./llm/fake/index.ts"),',
      "};",
      "",
    ]);
    assert.equal(
      registrySource([]).split("\n")[1],
      `export const adapterLoaders: ${LOADERS_TYPE} = {};`,
    );
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("the adapters registered for a port, by name; one bound instance per adapter", async () => {
  assert.deepEqual([...registeredAdapters(fixturePort).keys()].sort(), ["echo", "fake"]);
  assert.equal(registeredAdapters(fixturePort).get("echo"), echoAdapter);
  assert.deepEqual(fixtureFakeAdapter.requires, []);
  const echo = await getAdapter(fixturePort, "echo");
  assert.equal(echo, await getAdapter(fixturePort, "echo"));
  assert.notEqual(echo, await getAdapter(fixturePort, "fake"));
  await echo.greet({ name: "Ada" });
  assert.deepEqual(await (await getAdapter(fixturePort, "echo")).count(), { greetings: 1 });
});

test("a selector loads the one adapter it names; a loader that registers nothing or fails leaves nothing behind", async () => {
  const nowhere = "./fixtures/pattern/fixture/nowhere/index.ts";
  const loaders = {
    "fixture/lazy": () => import("./fixtures/pattern/fixture/lazy/index.ts"),
    "fixture/hollow": async () => {},
    "fixture/nowhere": () => import(nowhere),
  };
  assert.deepEqual(knownAdapterNames(fixturePort, loaders), [
    "echo",
    "fake",
    "hollow",
    "lazy",
    "nowhere",
  ]);
  assert.ok(!registeredAdapters(fixturePort).has("lazy"));
  const lazy = await resolveAdapter(fixturePort, "lazy", loaders);
  assert.ok(registeredAdapters(fixturePort).has("lazy"));
  assert.ok(!registeredAdapters(fixturePort).has("broken"), "nothing but the named adapter loads");
  assert.equal(lazy, await resolveAdapter(fixturePort, "lazy", loaders));
  await lazy.greet({ name: "Ada" });
  assert.deepEqual(await lazy.count(), { greetings: 1 });
  await assert.rejects(resolveAdapter(fixturePort, "hollow", loaders), (error: unknown) => {
    assert.ok(isAppError(error) && error.code === "adapter_invalid");
    assert.deepEqual(error.details, {
      port: "fixture",
      adapter: "hollow",
      reason: "the folder's index.ts registered no adapter of that name for the port",
    });
    return true;
  });
  await assert.rejects(
    resolveAdapter(fixturePort, "nowhere", loaders),
    (error: unknown) => (error as { code?: string }).code === "ERR_MODULE_NOT_FOUND",
  );
  await assert.rejects(resolveAdapter(fixturePort, "nope", loaders), (error: unknown) => {
    assert.ok(isAppError(error) && error.code === "provider_unknown");
    assert.deepEqual(error.details, {
      port: "fixture",
      selector: "nope",
      known: ["echo", "fake", "hollow", "lazy", "nowhere"],
    });
    return true;
  });

  let attempts = 0;
  defineAdapter(fixturePort, {
    name: "flaky",
    create: () => {
      attempts += 1;
      if (attempts === 1) throw new Error("not yet");
      return greeter();
    },
  });
  await assert.rejects(resolveAdapter(fixturePort, "flaky", {}), { message: "not yet" });
  const flaky = await resolveAdapter(fixturePort, "flaky", {});
  assert.equal(flaky, await resolveAdapter(fixturePort, "flaky", {}));
  assert.equal(attempts, 2);

  let halves = 0;
  defineAdapter(fixturePort, {
    name: "half",
    create: () => {
      halves += 1;
      return { greet: greeter().greet } as never;
    },
  });
  for (let round = 0; round < 2; round += 1) {
    await assert.rejects(
      resolveAdapter(fixturePort, "half", {}),
      (error: unknown) => isAppError(error) && error.code === "port_shape_mismatch",
    );
  }
  assert.equal(halves, 2, "a failed shape check caches nothing");
});
