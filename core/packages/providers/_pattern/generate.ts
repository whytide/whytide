// Writes registry.generated.ts (docs/rules/coding.md §3: a registry, never a central list): a loader
// per <port>/<adapter>/index.ts under the folder, a port being a folder with a port.ts, an adapter a
// folder inside it with an index.ts; `tests/`, `testing/` and `_*` folders are not adapters. The
// build, typecheck and test scripts run it first; git ignores *.generated.*.
//   node _pattern/generate.ts [dir]    the folder to scan, the package by default; the file goes inside it
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const SKIPPED = new Set(["tests", "testing", "node_modules", "dist"]);
const TYPE = "Readonly<Record<string, () => Promise<unknown>>>";

/** `<port>/<adapter>` for every adapter under `dir`, sorted. */
export function listAdapters(dir: string): string[] {
  const folders = (at: string) =>
    readdirSync(at, { withFileTypes: true })
      .filter(
        (entry) => entry.isDirectory() && !SKIPPED.has(entry.name) && !/^[._]/.test(entry.name),
      )
      .map((entry) => entry.name)
      .sort();
  return folders(dir)
    .filter((port) => existsSync(join(dir, port, "port.ts")))
    .flatMap((port) =>
      folders(join(dir, port))
        .filter((adapter) => existsSync(join(dir, port, adapter, "index.ts")))
        .map((adapter) => `${port}/${adapter}`),
    );
}

/** The module's text: `adapterLoaders`, one dynamic import per adapter, so that only the selected one loads. */
export function registrySource(adapters: readonly string[]): string {
  const entries = adapters
    .map((adapter) => `  "${adapter}": () => import("./${adapter}/index.ts"),\n`)
    .join("");
  return [
    '// Generated by _pattern/generate.ts: a loader per <port>/<adapter>/index.ts; never committed (README.md "The registry").',
    `export const adapterLoaders: ${TYPE} = {${entries ? `\n${entries}` : ""}};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  const dir = resolve(process.argv[2] ?? join(import.meta.dirname, ".."));
  const adapters = listAdapters(dir);
  const out = join(dir, "registry.generated.ts");
  const text = registrySource(adapters);
  // Written only when it changed: another package's `tsc -b` may be reading it.
  if (!existsSync(out) || readFileSync(out, "utf8") !== text) writeFileSync(out, text);
  process.stdout.write(`registry: ${adapters.length} adapter${adapters.length === 1 ? "" : "s"}\n`);
}
