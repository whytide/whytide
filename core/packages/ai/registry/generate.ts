// Writes registry/tasks.generated.ts (docs/rules/coding.md §3: a registry, never a central list): the
// URL of every core module's agents/<agent>/task.ts, sorted, for loadAgentTasks(). The build,
// typecheck and test scripts run it first; git ignores *.generated.*. Modules under ee/ are not
// scanned: core never imports ee/ (the module-boundaries rule).
//   node registry/generate.ts [root]    the folder that holds modules/, core/ by default
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const folders = (at: string) =>
  existsSync(at)
    ? readdirSync(at, { withFileTypes: true })
        .filter((entry) => entry.isDirectory() && !/^[._]/.test(entry.name))
        .map((entry) => entry.name)
        .sort()
    : [];

/** The file URL of every `<root>/modules/<module>/agents/<agent>/task.ts`; `_` and dot folders are skipped. */
export function listTaskFiles(root: string): string[] {
  const modules = join(root, "modules");
  return folders(modules).flatMap((module) =>
    folders(join(modules, module, "agents"))
      .map((agent) => join(modules, module, "agents", agent, "task.ts"))
      .filter((file) => existsSync(file))
      .map((file) => pathToFileURL(file).href),
  );
}

/** The module's text: `taskFiles`, the list loadAgentTasks() imports by default. */
export function taskListSource(files: readonly string[]): string {
  const entries = files.map((file) => `  ${JSON.stringify(file)},\n`).join("");
  return [
    '// Generated by registry/generate.ts: every core module\'s agents/<agent>/task.ts; never committed (README.md "Declaring a task").',
    `export const taskFiles: readonly string[] = [${entries ? `\n${entries}` : ""}];`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  const root = resolve(process.argv[2] ?? join(import.meta.dirname, "../../.."));
  const files = listTaskFiles(root);
  const out = join(import.meta.dirname, "tasks.generated.ts");
  const text = taskListSource(files);
  // Written only when it changed: another package's `tsc -b` may be reading it.
  if (!existsSync(out) || readFileSync(out, "utf8") !== text) writeFileSync(out, text);
  process.stdout.write(`agent tasks: ${files.length}\n`);
}
