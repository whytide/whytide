// Which zone a place is in (README "Time"; F11 §5.1; briefs RB-1.2.5, RB-12.2.1), as data for
// timeZoneOf (recipient-hours.ts). A table names the zone only: its offsets and daylight-saving
// changes are the runtime's Intl data, never a table here. A country added later is one line here
// and its row in tests/recipient-hours.test.ts.

/**
 * A state, province or territory: the names location texts give it, its usual abbreviation among
 * them, and the zone most of its people use.
 */
export type RegionZone = { readonly names: readonly string[]; readonly zone: string };

const region = (names: string[], zone: string): RegionZone =>
  Object.freeze({ names: Object.freeze(names), zone });

