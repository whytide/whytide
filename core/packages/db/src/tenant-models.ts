// The tenant client's model list (alpha-p1-045): `node src/cli.ts generate` parses prisma/schema and
// its subfolders with the schema lint's parser, once the client is current, and writes
// generated/tenant-models.ts, compiled and shipped with the client it describes. A tenant model is
// marked `/// tenant` or has a workspace_id column; every other model the parse saw is global; the
// client refuses a model the list does not name (src/tenant.ts). Relations are listed so that the
// client refuses them in every argument.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { packageRoot } from "./paths.ts";
import { parseSchema, schemaFiles } from "./schema-lint.ts";
import { columnOf } from "./tenancy-check.ts";

export type ModelScope = {
  /** Marked `/// tenant` or holding a workspace_id column. */
  readonly tenant: boolean;
  /** The field that holds workspace_id; null for a global model or a marked model without one. */
  readonly field: string | null;
  /** The fields whose type is a model. */
  readonly relations: readonly string[];
};
export type ModelScopes = Readonly<Record<string, ModelScope>>;

const schemaDir = join(packageRoot, "prisma", "schema");

/** Every model of the schema folder, with its scope. */
export function readModelScopes(dir = schemaDir): ModelScopes {
  const models = schemaFiles(dir).flatMap(
    (path) => parseSchema(path, readFileSync(path, "utf8")).models,
  );
  const names = new Set(models.map((model) => model.name));
  return Object.fromEntries(
    models.map((model) => {
      const field = model.fields.find((f) => !names.has(f.type) && columnOf(f) === "workspace_id");
      const relations = model.fields.filter((f) => names.has(f.type)).map((f) => f.name);
      const scope: ModelScope = {
        tenant: model.tenant || field !== undefined,
        field: field?.name ?? null,
        relations,
      };
      return [model.name, scope];
    }),
  );
}

/** Writes generated/tenant-models.ts from the schema folder when it changed; true when it did. */
export function writeModelScopes(
  dir = schemaDir,
  out = join(packageRoot, "generated", "tenant-models.ts"),
): boolean {
  const list = JSON.stringify(readModelScopes(dir), null, 2);
  const text = `// Generated by \`node src/cli.ts generate\` from prisma/schema (src/tenant-models.ts). Do not edit.\nimport type { ModelScopes } from "../src/tenant-models.ts";\n\nexport const modelScopes: ModelScopes = ${list};\n`;
  if (existsSync(out) && readFileSync(out, "utf8") === text) return false;
  writeFileSync(out, text);
  return true;
}
